import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// Review and commit this public manifest only after real HTTPS and App Attest
// verification. Generation never reads environment variables or secret files.
export function generateResearchAppConfiguration(manifest) {
  if (!manifest || Object.keys(manifest).sort().join(',') !== 'production,staging') throw Error('invalid_deployment_manifest');
  const entries = Object.entries(manifest).map(([lane, entry]) => {
    if (entry === null) return {lane, host: null, url: ''};
    if (!entry || Object.keys(entry).sort().join(',') !== 'baseURL,verificationReceipt' ||
        typeof entry.verificationReceipt !== 'string' || !/^[a-zA-Z0-9._/-]{3,200}$/.test(entry.verificationReceipt)) throw Error('missing_deployment_receipt');
    const url = new URL(entry.baseURL);
    if (url.protocol !== 'https:' || url.username || url.password || url.port || url.search || url.hash || url.pathname !== '/' ||
        !/^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])$/.test(url.hostname) || !url.hostname.includes('.') ||
        /(^|\.)(localhost|local|invalid|example|test)$|(^|\.)(trycloudflare\.com|ngrok-free\.app|ngrok\.io)$/.test(url.hostname) ||
        /^\d+(\.\d+){3}$/.test(url.hostname) || url.hostname.includes('..') || entry.baseURL !== url.origin + '/') throw Error('invalid_deployment_origin');
    return {lane, host: url.hostname, url: url.origin + '/'};
  });
  if (entries[0].host && entries[0].host === entries[1].host) throw Error('deployment_lanes_must_differ');
  const swift = '// Generated by backend/scripts/configure-research-app.js from reviewed public deployment metadata.\n// An absent deployment remains unavailable; no placeholder host is trusted.\nnonisolated enum ResearchDeploymentIdentity {\n' + entries.map(x=>`    static let ${x.lane}Host: String? = ${x.host ? JSON.stringify(x.host) : 'nil'}\n`).join('') + '}\n';
  const xcconfig = '// Generated from ResearchDeployment.json; no secrets belong here.\n' + entries.map(x=>`${x.lane.toUpperCase()}_BACKEND_BASE_URL =${x.url ? ' '+x.url.replace('https://','https:/$()/') : ''}\n${x.lane.toUpperCase()}_RESEARCH_ENABLED = ${Boolean(x.host)}\n`).join('');
  return {swift, xcconfig};
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const generated = generateResearchAppConfiguration(JSON.parse(fs.readFileSync(path.join(root,'Configuration/ResearchDeployment.json'),'utf8')));
  for (const [relative, content] of [['TrailMind/Services/ResearchDeploymentIdentity.swift',generated.swift],['Configuration/ResearchDeployment.xcconfig',generated.xcconfig]]) {
    const target = path.join(root,relative);
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(target,'utf8') !== content) throw Error('deployment_configuration_drift');
    } else fs.writeFileSync(target,content);
  }
  console.log('Research deployment configuration verified; no credentials read.');
}
